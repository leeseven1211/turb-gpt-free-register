_PLACEHOLDER_EMPTY = {
    "", "-", "—", "无", "空", "none", "null", "n/a", "na", "未设置", "未配置",
}


def _normalize_config_value(value, vtype: str):
    """把前端/历史占位空值规范化，避免 '-' 被当成真实配置。"""
    if vtype == "str":
        s = "" if value is None else str(value).strip()
        if s.lower() in {x.lower() for x in _PLACEHOLDER_EMPTY}:
            return ""
        return s
    if vtype == "list_str_multiline":
        if value is None:
            return []
        if isinstance(value, str):
            lines = value.splitlines()
        elif isinstance(value, (list, tuple)):
            lines = list(value)
        else:
            lines = [str(value)]
        out = []
        for item in lines:
            s = str(item or "").strip()
            if not s or s.lower() in {x.lower() for x in _PLACEHOLDER_EMPTY}:
                continue
            out.append(s)
        return out
    return value


def _format_literal(value, vtype: str) -> str:
    """把前端传来的值格式化成 Python 字面量字符串。"""
    if vtype == "bool":
        if isinstance(value, str):
            value = value.strip().lower() in ("true", "1", "yes", "on")
        return "True" if value else "False"
    if vtype == "int":
        return str(int(value))
    if vtype == "float":
        return repr(float(value))
    if vtype == "str":
        s = str(value)
        # 用 repr 保证转义安全，但统一成双引号风格
        return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'
    raise ValueError(f"_format_literal 不支持的类型: {vtype}")


def _replace_scalar(source: str, key: str, literal: str) -> str:
    """替换 `KEY[: 类型] = 旧值` 行的右值，保留行内注释和类型标注。"""
    pattern = re.compile(
        rf"^(?P<head>{re.escape(key)}\s*(?::[^=\n]+)?=\s*)"
        rf"(?P<val>.+?)"
        rf"(?P<tail>\s*(?:#.*)?)$",
        re.MULTILINE,
    )
    if not pattern.search(source):
        raise ValueError(f"未在源码中找到可替换的赋值: {key}")
    return pattern.sub(lambda m: f"{m.group('head')}{literal}{m.group('tail')}", source, count=1)


def _replace_proxy_pool(source: str, lines: list[str]) -> str:
    """整块替换 PROXY_POOL = [ ... ] 列表字面量（保留前面的赋值头）。"""
    items = [ln.strip() for ln in lines if ln.strip()]
    if items:
        body = "\n".join(
            '    "' + it.replace("\\", "\\\\").replace('"', '\\"') + '",'
            for it in items
        )
        literal = "[\n" + body + "\n]"
    else:
        literal = "[]"

    # 匹配 PROXY_POOL = [ ... ]（含跨行），用 AST 定位起止偏移最稳
    tree = ast.parse(source)
    for node in tree.body:
        targets = node.targets if isinstance(node, ast.Assign) else (
            [node.target] if isinstance(node, ast.AnnAssign) else []
        )
        for t in targets:
            if isinstance(t, ast.Name) and t.id == "PROXY_POOL":
                src_lines = source.splitlines(keepends=True)
                start = node.value.lineno          # 值（[）所在行，1-based
                end = node.value.end_lineno        # 值（]）所在行，1-based
                col = node.value.col_offset         # [ 在起始行的列偏移
                # 保留起始行 [ 之前的内容（即 "PROXY_POOL = " 或 "PROXY_POOL: list = "）
                prefix = src_lines[start - 1][:col]
                # 保留结束行 ] 之后的内容（行内注释 / 换行）
                end_line = src_lines[end - 1]
                suffix = end_line[node.value.end_col_offset:]
                new_lines = (
                    src_lines[: start - 1]
                    + [prefix + literal + suffix]
                    + src_lines[end:]
                )
                return "".join(new_lines)
    raise ValueError("未找到 PROXY_POOL 赋值")


def _atomic_write(path: Path, text: str) -> None:
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    tmp.replace(path)


def _format_env_value(value, vtype: str) -> str:
    """把前端值格式化成适合写入 .env 的字符串。"""
    if vtype == "bool":
        if isinstance(value, str):
            value = value.strip().lower() in ("true", "1", "yes", "on", "y")
        return "True" if value else "False"
    if vtype == "int":
        return str(int(value))
    if vtype == "float":
        return repr(float(value))
    if vtype == "list_str_multiline":
        lines = _normalize_config_value(value, vtype)
        return "\n".join(lines) if lines else "[]"
    if vtype == "str":
        return _normalize_config_value(value, vtype)
    return "" if value is None else str(value)


_CONFIG_WRITE_LOCK = threading.RLock()


def update_config(updates: dict) -> dict:
    """严格校验并原子保存一批 WebUI 配置。

    候选值全部通过 schema 后才会写 `.env`。写盘或热加载任一步失败时恢复
    原文件和进程环境；``config.reload_all`` 自身也提供模块级回滚。
    """
    if not updates:
        return {
            "updated": [],
            "ignored": [],
            "env_updated": [],
            "reloaded": False,
            "reload_modules": [],
            "restart_required": [],
        }

    normalized = validate_config_updates(updates)
    env_updates = {
        key: _format_env_value(value, _FIELD_BY_KEY[key]["type"])
        for key, value in normalized.items()
    }

    from config.env_loader import env_path, load_env, restore_environment, write_env_values
    import config as config_package

    path = env_path()
    with _CONFIG_WRITE_LOCK:
        # 保存前固定已发布的旧版本；reload 成功前不会替换它，失败时任务
        # 读者仍能继续使用同一个 snapshot 对象。
        non_sensitive_snapshot()
        old_exists = path.exists()
        old_bytes = path.read_bytes() if old_exists else None
        old_environment = dict(os.environ)
        environment_expected = dict(os.environ)
        try:
            # 在写 `.env` 前严格校验整套候选环境；候选 snapshot 仍未发布。
            # load_env 遵守 PYTHON_DOTENV_DISABLED，隔离测试不会被工作区 dotenv 污染。
            load_env(override=True)
            environment_expected = dict(os.environ)
            candidate_environment = dict(os.environ)
            candidate_environment.update(env_updates)
            build_non_sensitive_snapshot(candidate_environment, strict=True)
            env_updated = write_env_values(env_updates)
            environment_expected = dict(os.environ)
            reload_modules = config_package.reload_all()
        except Exception:
            # 恢复精确的单个 .env 文件；不会触碰其他目录或运行时数据。
            if old_exists:
                path.write_bytes(old_bytes or b"")
            elif path.exists():
                path.unlink()
            restore_environment(old_environment, environment_expected)
            raise

    updated = list(normalized)
    return {
        "updated": updated,
        "ignored": [],
        "env_updated": env_updated,
        "reloaded": True,
        "reload_modules": reload_modules,
        "restart_required": [key for key in updated if key in RESTART_REQUIRED_KEYS],
    }
