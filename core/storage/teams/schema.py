# -*- coding: utf-8 -*-
"""Team 领域表及索引；事实与执行引用保存在同一个 PostgreSQL schema。"""
from __future__ import annotations

import threading

from core.storage import postgres, records

_LOCK = threading.RLock()
_READY_KEY = None
_SCHEMA_VERSION = 1
_ROLES = "'owner','admin','member','unknown'"
_MEMBERSHIP_STATES = "'joined','left','unconfirmed'"
_INVITATION_STATES = "'not_sent','pending','accepted','revoked','expired','unconfirmed'"
_EXECUTION_STATES = (
    "'none','queued','running','waiting','cancelling','settling','stopping',"
    "'success','partial_success','failed','stopped','cancelled','interrupted',"
    "'deactivated','unsupported'"
)
_JOIN_STAGES = (
    "'queued','manager_verify','state_check','invite','member_auth','accept',"
    "'member_verify','persist','complete'"
)


def _table(name: str) -> str:
    return postgres.qualified(name)


def reset_ready() -> None:
    """切换数据库或 schema 后清除进程内初始化缓存。"""
    global _READY_KEY
    with _LOCK:
        _READY_KEY = None


def _apply(cur) -> None:
    account_table = _table(records.ACCOUNTS.name)
    workspaces = _table("team_workspaces")
    members = _table("team_members")
    invitations = _table("team_invitations")
    requests = _table("team_join_requests")
    cur.execute(
        f"""
        CREATE TABLE IF NOT EXISTS {workspaces} (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            workspace_id TEXT NOT NULL UNIQUE CHECK (btrim(workspace_id) <> ''),
            manager_account_id BIGINT NOT NULL REFERENCES {account_table}(id),
            revision BIGINT NOT NULL DEFAULT 1 CHECK (revision > 0),
            manager_revision BIGINT NOT NULL DEFAULT 1 CHECK (manager_revision > 0),
            name TEXT,
            display_name TEXT CHECK (display_name IS NULL OR char_length(display_name) <= 120),
            role TEXT NOT NULL DEFAULT 'unknown' CHECK (role IN ({_ROLES})),
            purchased_seats INTEGER CHECK (purchased_seats >= 0),
            planned_member_limit INTEGER CHECK (planned_member_limit > 0),
            confirmed_member_count INTEGER CHECK (confirmed_member_count >= 0),
            pending_invite_count INTEGER CHECK (pending_invite_count >= 0),
            members_complete BOOLEAN NOT NULL DEFAULT FALSE,
            invitations_complete BOOLEAN NOT NULL DEFAULT FALSE,
            members_synced_at TIMESTAMPTZ,
            invitations_synced_at TIMESTAMPTZ,
            last_synced_at TIMESTAMPTZ,
            last_sync_status TEXT NOT NULL DEFAULT 'never'
                CHECK (last_sync_status IN ('never','queued','running','success',
                    'partial_success','failed','interrupted')),
            permission_verified_at TIMESTAMPTZ,
            permissions JSONB NOT NULL DEFAULT '{{}}'::jsonb
                CHECK (jsonb_typeof(permissions) = 'object'),
            last_snapshot_at TIMESTAMPTZ,
            snapshot_sequence BIGINT NOT NULL DEFAULT 0 CHECK (snapshot_sequence >= 0),
            created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
            updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
            UNIQUE(id, workspace_id)
        )
        """
    )
    cur.execute(
        f"""
        CREATE TABLE IF NOT EXISTS {members} (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            team_id BIGINT NOT NULL REFERENCES {workspaces}(id),
            identity_key TEXT NOT NULL CHECK (btrim(identity_key) <> ''),
            remote_user_id TEXT,
            email TEXT,
            account_id BIGINT REFERENCES {account_table}(id),
            role TEXT NOT NULL DEFAULT 'unknown' CHECK (role IN ({_ROLES})),
            membership_state TEXT NOT NULL DEFAULT 'unconfirmed'
                CHECK (membership_state IN ({_MEMBERSHIP_STATES})),
            joined_at TIMESTAMPTZ,
            last_verified_at TIMESTAMPTZ,
            last_task_id BIGINT,
            last_run_id BIGINT,
            execution_status TEXT NOT NULL DEFAULT 'none'
                CHECK (execution_status IN ({_EXECUTION_STATES})),
            source_revision BIGINT NOT NULL DEFAULT 0 CHECK (source_revision >= 0),
            absent_complete_count INTEGER NOT NULL DEFAULT 0 CHECK (absent_complete_count >= 0),
            created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
            updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
            UNIQUE(team_id, identity_key)
        )
        """
    )
    cur.execute(
        f"""
        CREATE TABLE IF NOT EXISTS {invitations} (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            team_id BIGINT NOT NULL REFERENCES {workspaces}(id),
            target_key TEXT NOT NULL CHECK (btrim(target_key) <> ''),
            account_id BIGINT REFERENCES {account_table}(id),
            email_snapshot TEXT,
            remote_invitation_id TEXT,
            invitation_state TEXT NOT NULL DEFAULT 'not_sent'
                CHECK (invitation_state IN ({_INVITATION_STATES})),
            membership_state TEXT NOT NULL DEFAULT 'unconfirmed'
                CHECK (membership_state IN ({_MEMBERSHIP_STATES})),
            execution_status TEXT NOT NULL DEFAULT 'none'
                CHECK (execution_status IN ({_EXECUTION_STATES})),
            stage TEXT NOT NULL DEFAULT 'queued' CHECK (stage IN ({_JOIN_STAGES})),
            waiting_reason_code TEXT,
            reason_code TEXT,
            error_message TEXT,
            last_task_id BIGINT,
            last_run_id BIGINT,
            active BOOLEAN NOT NULL DEFAULT TRUE,
            seat_reserved BOOLEAN NOT NULL DEFAULT FALSE,
            execution_fence BIGINT NOT NULL DEFAULT 0 CHECK (execution_fence >= 0),
            manager_revision BIGINT,
            local_saved BOOLEAN NOT NULL DEFAULT FALSE,
            last_verified_at TIMESTAMPTZ,
            absent_complete_count INTEGER NOT NULL DEFAULT 0 CHECK (absent_complete_count >= 0),
            created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
            updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
            UNIQUE(team_id, target_key),
            UNIQUE(id, team_id)
        )
        """
    )
    cur.execute(
        f"""
        CREATE TABLE IF NOT EXISTS {_table('team_account_ownership')} (
            account_id BIGINT PRIMARY KEY REFERENCES {account_table}(id),
            team_id BIGINT NOT NULL REFERENCES {workspaces}(id),
            kind TEXT NOT NULL,
            invitation_id BIGINT,
            absent_complete_count INTEGER NOT NULL DEFAULT 0 CHECK (absent_complete_count >= 0),
            created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
            updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
            FOREIGN KEY (invitation_id, team_id) REFERENCES {invitations}(id, team_id)
        )
        """
    )
    cur.execute(
        f"""
        CREATE TABLE IF NOT EXISTS {_table('team_binding_probes')} (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            manager_account_id BIGINT NOT NULL REFERENCES {account_table}(id),
            target_workspace_id TEXT,
            status TEXT NOT NULL DEFAULT 'queued'
                CHECK (status IN ('queued','running','success','failed','cancelled','interrupted')),
            stage TEXT NOT NULL DEFAULT 'queued'
                CHECK (stage IN ('queued','manager_auth','workspace_discovery',
                    'permission_check','complete')),
            revision BIGINT NOT NULL DEFAULT 1 CHECK (revision > 0),
            task_id BIGINT,
            run_id BIGINT,
            workspaces JSONB NOT NULL DEFAULT '[]'::jsonb
                CHECK (jsonb_typeof(workspaces) = 'array'),
            suggested_workspace_id TEXT,
            completed_at TIMESTAMPTZ,
            expires_at TIMESTAMPTZ,
            error_info JSONB,
            created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
            updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
            CHECK (expires_at IS NULL OR (completed_at IS NOT NULL AND expires_at >= completed_at))
        )
        """
    )
    cur.execute(
        f"""
        CREATE TABLE IF NOT EXISTS {_table('team_request_receipts')} (
            idempotency_key TEXT PRIMARY KEY,
            path TEXT NOT NULL,
            fingerprint TEXT NOT NULL,
            response_json JSONB NOT NULL,
            status_code INTEGER NOT NULL CHECK (status_code BETWEEN 100 AND 599),
            created_at TIMESTAMPTZ NOT NULL DEFAULT now()
        )
        """
    )
    cur.execute(
        f"""
        CREATE TABLE IF NOT EXISTS {requests} (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            team_id BIGINT NOT NULL REFERENCES {workspaces}(id),
            operation TEXT NOT NULL DEFAULT 'join' CHECK (operation IN ('join','continue','retry')),
            status TEXT NOT NULL DEFAULT 'preparing'
                CHECK (status IN ('preparing','queued','running','waiting','success',
                    'partial_success','failed','stopped','cancelled','interrupted')),
            selection_id BIGINT UNIQUE,
            selection_revision BIGINT CHECK (selection_revision > 0),
            requested_count INTEGER NOT NULL CHECK (requested_count >= 0),
            unique_count INTEGER NOT NULL CHECK (unique_count >= 0),
            duplicate_count INTEGER NOT NULL DEFAULT 0 CHECK (duplicate_count >= 0),
            task_id BIGINT,
            run_id BIGINT,
            batch_id BIGINT,
            waiting_reason_code TEXT,
            capacity JSONB NOT NULL DEFAULT '{{}}'::jsonb CHECK (jsonb_typeof(capacity) = 'object'),
            created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
            updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
            CHECK (requested_count = unique_count + duplicate_count),
            CHECK ((selection_id IS NULL) = (selection_revision IS NULL)),
            UNIQUE(id, team_id)
        )
        """
    )
    cur.execute(
        f"""
        CREATE TABLE IF NOT EXISTS {_table('team_join_request_items')} (
            request_id BIGINT NOT NULL REFERENCES {requests}(id),
            ordinal INTEGER NOT NULL CHECK (ordinal >= 0),
            account_id BIGINT,
            invitation_id BIGINT REFERENCES {invitations}(id),
            input_invitation_id BIGINT,
            email_snapshot TEXT,
            acceptance_status TEXT NOT NULL DEFAULT 'pending'
                CHECK (acceptance_status IN ('pending','accepted','reused','skipped','failed')),
            task_id BIGINT,
            run_id BIGINT,
            execution_status TEXT NOT NULL DEFAULT 'none'
                CHECK (execution_status IN ({_EXECUTION_STATES})),
            reason_code TEXT,
            message TEXT,
            created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
            updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
            PRIMARY KEY(request_id, ordinal)
        )
        """
    )
    cur.execute(
        f"""
        CREATE TABLE IF NOT EXISTS {_table('team_auth_contexts')} (
            account_id BIGINT NOT NULL REFERENCES {account_table}(id),
            team_id BIGINT NOT NULL REFERENCES {workspaces}(id),
            workspace_id TEXT NOT NULL,
            identity_ref TEXT NOT NULL,
            encrypted_context TEXT NOT NULL,
            revision BIGINT NOT NULL DEFAULT 1 CHECK (revision > 0),
            verified_at TIMESTAMPTZ,
            created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
            updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
            PRIMARY KEY(account_id, team_id),
            FOREIGN KEY (team_id, workspace_id) REFERENCES {workspaces}(id, workspace_id)
        )
        """
    )
    cur.execute(
        f"""
        CREATE TABLE IF NOT EXISTS {_table('team_execution_receipts')} (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            team_id BIGINT NOT NULL REFERENCES {workspaces}(id),
            invitation_id BIGINT,
            request_key TEXT NOT NULL UNIQUE,
            workspace_id TEXT NOT NULL,
            manager_account_id BIGINT NOT NULL REFERENCES {account_table}(id),
            manager_revision BIGINT NOT NULL CHECK (manager_revision > 0),
            execution_fence BIGINT NOT NULL CHECK (execution_fence >= 0),
            kind TEXT NOT NULL,
            facts JSONB NOT NULL DEFAULT '{{}}'::jsonb CHECK (jsonb_typeof(facts) = 'object'),
            created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
            FOREIGN KEY (invitation_id, team_id) REFERENCES {invitations}(id, team_id),
            FOREIGN KEY (team_id, workspace_id) REFERENCES {workspaces}(id, workspace_id)
        )
        """
    )
    cur.execute(
        f"""
        CREATE TABLE IF NOT EXISTS {_table('team_outbox')} (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            kind TEXT NOT NULL,
            aggregate_type TEXT NOT NULL,
            aggregate_id BIGINT NOT NULL,
            payload JSONB NOT NULL DEFAULT '{{}}'::jsonb CHECK (jsonb_typeof(payload) = 'object'),
            dedupe_key TEXT NOT NULL UNIQUE,
            status TEXT NOT NULL DEFAULT 'pending'
                CHECK (status IN ('pending','processing','completed','failed')),
            attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
            available_at TIMESTAMPTZ NOT NULL DEFAULT now(),
            lease_token TEXT,
            lease_until TIMESTAMPTZ,
            last_error TEXT,
            created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
            updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
            CHECK (status <> 'processing' OR (lease_token IS NOT NULL AND lease_until IS NOT NULL))
        )
        """
    )
    indexes = (
        ("team_workspaces_manager_idx", "team_workspaces", "(manager_account_id, id DESC)"),
        ("team_workspaces_role_idx", "team_workspaces", "(role, id DESC)"),
        ("team_workspaces_sync_idx", "team_workspaces", "(last_sync_status, id DESC)"),
        ("team_members_state_idx", "team_members", "(team_id, membership_state, id)"),
        ("team_members_role_idx", "team_members", "(team_id, role, id)"),
        ("team_members_account_idx", "team_members", "(account_id, team_id) WHERE account_id IS NOT NULL"),
        ("team_members_joined_account_idx", "team_members",
         "(account_id, team_id) WHERE membership_state='joined' AND account_id IS NOT NULL"),
        ("team_members_unlinked_email_idx", "team_members",
         "(lower(btrim(COALESCE(email,'')))) WHERE account_id IS NULL AND membership_state='joined'"),
        ("team_invitations_state_idx", "team_invitations",
         "(team_id, invitation_state, updated_at DESC, id DESC)"),
        ("team_invitations_membership_idx", "team_invitations",
         "(team_id, membership_state, updated_at DESC, id DESC)"),
        ("team_invitations_execution_idx", "team_invitations",
         "(team_id, execution_status, updated_at DESC, id DESC)"),
        ("team_invitations_stage_idx", "team_invitations",
         "(team_id, stage, updated_at DESC, id DESC)"),
        ("team_invitations_list_idx", "team_invitations", "(team_id, updated_at DESC, id DESC)"),
        ("team_invitations_active_idx", "team_invitations", "(team_id, target_key) WHERE active"),
        ("team_invitations_processing_idx", "team_invitations",
         "(team_id, account_id, target_key, updated_at) WHERE active AND execution_status IN "
         "('queued','running','waiting','cancelling','settling','stopping')"),
        ("team_invitations_account_idx", "team_invitations", "(account_id, team_id) WHERE account_id IS NOT NULL"),
        ("team_invitations_unlinked_email_idx", "team_invitations",
         "(lower(btrim(COALESCE(email_snapshot,'')))) WHERE account_id IS NULL"),
        ("team_account_ownership_team_idx", "team_account_ownership", "(team_id, account_id)"),
        ("team_binding_probes_status_idx", "team_binding_probes", "(status, id)"),
        ("team_join_requests_team_idx", "team_join_requests", "(team_id, id DESC)"),
        ("team_join_request_items_status_idx", "team_join_request_items",
         "(request_id, acceptance_status, ordinal)"),
        ("team_join_request_items_invitation_idx", "team_join_request_items",
         "(invitation_id, request_id) WHERE invitation_id IS NOT NULL"),
        ("team_execution_receipts_invitation_idx", "team_execution_receipts", "(invitation_id, id)"),
        ("team_outbox_pending_idx", "team_outbox",
         "(available_at, id) WHERE status IN ('pending','processing')"),
    )
    for name, table, definition in indexes:
        cur.execute(f"CREATE INDEX IF NOT EXISTS {postgres.quote_identifier(name)} ON {_table(table)} {definition}")
    unique_indexes = (
        ("team_members_remote_user_uidx", "team_members",
         "(team_id, remote_user_id) WHERE remote_user_id IS NOT NULL"),
        ("team_invitations_remote_uidx", "team_invitations",
         "(team_id, remote_invitation_id) WHERE remote_invitation_id IS NOT NULL"),
        ("team_invitations_account_uidx", "team_invitations",
         "(team_id, account_id) WHERE account_id IS NOT NULL"),
    )
    for name, table, definition in unique_indexes:
        cur.execute(
            f"CREATE UNIQUE INDEX IF NOT EXISTS {postgres.quote_identifier(name)} "
            f"ON {_table(table)} {definition}"
        )


def init() -> None:
    """串行完成 Team 领域迁移，不连接额外数据库，也不绕过生产保护。"""
    global _READY_KEY
    key = (postgres.database_url(), postgres.schema_name(), _SCHEMA_VERSION)
    with _LOCK:
        if _READY_KEY == key:
            return
        postgres.ensure_schema()
        records.init()
        with postgres.connect() as conn, conn.cursor() as cur:
            records.advisory_xact_lock(conn, f"team-store-schema:{postgres.schema_name()}")
            migrations = _table("team_schema_migrations")
            cur.execute(
                f"CREATE TABLE IF NOT EXISTS {migrations} "
                "(version INTEGER PRIMARY KEY,completed_at TIMESTAMPTZ NOT NULL DEFAULT now())"
            )
            cur.execute(f"SELECT 1 FROM {migrations} WHERE version=%s", (_SCHEMA_VERSION,))
            if cur.fetchone() is None:
                _apply(cur)
                cur.execute(f"INSERT INTO {migrations}(version) VALUES (%s)", (_SCHEMA_VERSION,))
        _READY_KEY = key


def ensure_schema() -> None:
    """保留明确的领域初始化入口，供启动和只读查询复用。"""
    init()
