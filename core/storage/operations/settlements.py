def _disposition_cur(cur, ticket):
    cur.execute(f'''SELECT * FROM {_common._table('operation_settlement_dispositions')}
        WHERE domain_id=%s AND run_uuid=%s AND execution_id=%s AND permit_id=%s AND ticket_id=%s''',
        tuple(str(ticket[key]) for key in ('domain_id','run_uuid','execution_id','permit_id','ticket_id')))
    row = cur.fetchone()
    if row is None:
        return None
    result = _common._decode(row['result'])
    if _digest(result) != row['result_digest']:
        raise _protocol().OperationSettlementConflict('recovery disposition integrity conflict')
    return {**(_common._row(dict(row)) or {}), 'result': result}


def _resource_snapshot(cur, run_id):
    cur.execute(f'''SELECT id,resource_uuid,resource_type,external_id,state,detail
        FROM {_common._table('operation_resources')} WHERE run_id=%s AND state <> 'released'
        ORDER BY id FOR UPDATE''',(int(run_id),))
    resources=[]
    for row in cur.fetchall():
        detail=_common._decode(row.get('detail')) or {}
        resource={'resource_id':int(row['id']),'resource_uuid':str(row['resource_uuid']),
            'resource_type':str(row.get('resource_type') or ''),'external_id':str(row.get('external_id') or ''),
            'execution_id':str(detail.get('execution_id') or ''),'state':str(row['state'])}
        if 'proxy_pool_child' in detail:
            resource['proxy_pool_child']=detail['proxy_pool_child']
        resources.append(resource)
    return resources


def write_disposition(cur, *, ticket, result, kind='orphan_recovery'):
    """Append an independently proved recovery, never the lost business result."""
    ticket = _thaw(ticket)
    result = _thaw(result)
    if (kind != 'orphan_recovery' or result.get('original_intent_committed') is not False
            or result.get('resource_disposition') not in {'no_blocking_resources','cleanup_pending'}
            or result.get('recovery_reason') != 'worker_exit_confirmed'
            or not result.get('event_uuid') or result.get('status') not in _common._TERMINAL_STATUSES):
        raise ValueError('invalid independent recovery disposition')
    for key in ('domain_id','run_id','run_uuid','execution_id','permit_id','ticket_id'):
        if not ticket.get(key):
            raise ValueError('incomplete independent recovery ticket')
    existing = _disposition_cur(cur, ticket)
    resources=_resource_snapshot(cur,int(ticket['run_id']))
    if result['resource_disposition']=='no_blocking_resources' and resources:
        raise _protocol().OperationSettlementFenced('original physical resources are not disposed')
    result={**result,'resources':resources}
    safe_result = _common._scrub(result)
    if safe_result != result:
        raise ValueError('recovery disposition contains private data')
    if existing:
        if existing['result_digest'] != _digest(safe_result):
            raise _protocol().OperationSettlementConflict('independent recovery disposition conflict')
        return existing
    cur.execute(f'''INSERT INTO {_common._table('operation_settlement_dispositions')}
        (domain_id,run_id,run_uuid,execution_id,permit_id,ticket_id,disposition_kind,
         result,result_digest,original_intent_committed)
        VALUES (%s,%s,%s,%s,%s,%s,%s,%s::jsonb,%s,FALSE) RETURNING *''',
        (str(ticket['domain_id']), int(ticket['run_id']), str(ticket['run_uuid']),
         str(ticket['execution_id']), str(ticket['permit_id']), str(ticket['ticket_id']),
         kind, _json(safe_result), _digest(safe_result)))
    return _common._row(dict(cur.fetchone()))


def read_disposition(ticket, *, domain, conn=None, deadline=None):
    _verify_domain_identity(domain)
    from psycopg.rows import dict_row
    ticket = _thaw(ticket)
    canonical=hashlib.sha256(json.dumps(
        [domain.database_url,domain.operation_schema,domain.permit_schema],
        ensure_ascii=True,separators=(',',':')).encode()).hexdigest()
    if str(domain.domain_id)!=canonical:
        raise _protocol().OperationSettlementFenced('settlement domain identity mismatch')
    if str(ticket.get('domain_id')) != str(domain.domain_id):
        raise _protocol().OperationSettlementFenced('recovery disposition domain mismatch')
    with _common.settlement_scope(domain, deadline=deadline):
        with (_common._connect() if conn is None else nullcontext(conn)) as current, current.cursor(row_factory=dict_row) as cur:
            return _disposition_cur(cur, ticket)


