def _protocol():
    from core.operations import settlement_contracts
    return settlement_contracts


def _thaw(value):
    return _protocol().thaw(value)


def _digest(value) -> str:
    return hashlib.sha256(json.dumps(value, ensure_ascii=False, sort_keys=True,
                                     separators=(',', ':'), allow_nan=False).encode('utf-8')).hexdigest()


def _json(value) -> str:
    return json.dumps(value, ensure_ascii=False, separators=(',', ':'), allow_nan=False)


def _verify_domain_identity(domain):
    canonical=hashlib.sha256(json.dumps(
        [domain.database_url,domain.operation_schema,domain.permit_schema],
        ensure_ascii=True,separators=(',',':')).encode()).hexdigest()
    if str(domain.domain_id)!=canonical:
        raise _protocol().OperationSettlementFenced('settlement domain identity mismatch')


def _identity(intent, domain) -> dict:
    _verify_domain_identity(domain)
    origin = _thaw(intent.origin)
    if not isinstance(origin, dict):
        raise ValueError('settlement origin must be an object')
    for key in ('run_id', 'run_uuid', 'execution_id', 'permit_id', 'ticket_id', 'domain_id'):
        if not origin.get(key):
            raise ValueError(f'settlement origin missing {key}')
    if str(origin['domain_id']) != str(domain.domain_id):
        raise _protocol().OperationSettlementFenced('settlement domain mismatch')
    canonical=hashlib.sha256(json.dumps(
        [domain.database_url,domain.operation_schema,domain.permit_schema],
        ensure_ascii=True,separators=(',',':')).encode()).hexdigest()
    if str(domain.domain_id)!=canonical:
        raise _protocol().OperationSettlementFenced('settlement domain identity mismatch')
    if intent.kind not in {'terminal', 'defer'} or not str(intent.transition_id):
        raise ValueError('invalid settlement transition')
    if int(intent.version) != _RECEIPT_VERSION:
        raise ValueError('unsupported settlement protocol version')
    for field in ('operation_schema', 'permit_schema'):
        if origin.get(field) and str(origin[field]) != str(getattr(domain, field)):
            raise _protocol().OperationSettlementFenced('settlement schema mismatch')
    return origin


