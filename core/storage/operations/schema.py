_LOCK = threading.RLock()


_READY_KEY = ""
_FORCE_SCHEMA_CHECK = False
# 修改统一任务表、索引或结算域结构时递增版本。
_SCHEMA_VERSION = 1
_SCHEMA_MIGRATIONS = "operation_schema_migrations"


def _ready_key() -> tuple[str, str, str]:
    return postgres_store.database_url(), _common._schema_name(), postgres_store.schema_name()


def reset_operation_ready() -> None:
    """强制下次初始化重新检查统一任务表。"""
    global _READY_KEY, _FORCE_SCHEMA_CHECK
    with _LOCK:
        _READY_KEY = ""
        _FORCE_SCHEMA_CHECK = True


def _migration_completed(cur, domain_id: str) -> bool:
    table = _common._table(_SCHEMA_MIGRATIONS)
    cur.execute("SELECT to_regclass(%s) AS migration_table", (table,))
    if cur.fetchone()["migration_table"] is None:
        return False
    cur.execute(f"SELECT 1 FROM {table} WHERE domain_id = %s AND version = %s", (domain_id, _SCHEMA_VERSION))
    return cur.fetchone() is not None


