def _backfill_account_states(cur) -> None:
    cur.execute(
        f"""
        UPDATE {postgres_store.qualified(record_store.ACCOUNTS.name)} account
        SET codex_credential_state=CASE
                WHEN account.deactivated
                  OR account.codex_status='deactivated'
                  OR account.codex_credential_state='deactivated'
                THEN 'deactivated'
                WHEN account.codex_status='success' OR EXISTS (
                    SELECT 1 FROM {postgres_store.qualified(record_store.CODEX_CREDENTIALS.name)} credential
                    WHERE credential.archived IS FALSE
                      AND LOWER(COALESCE(credential.email, ''))=LOWER(account.email)
                ) THEN 'valid'
                ELSE 'none'
            END,
            codex_execution_status=COALESCE(account.codex_execution_status, 'empty'),
            codex_last_run_status=COALESCE(
                account.codex_last_run_status,
                CASE
                    WHEN account.codex_status='success' THEN 'success'
                    WHEN account.codex_status IN ('failed','stopped','deactivated','interrupted') THEN account.codex_status
                    ELSE NULL
                END
            )
        WHERE account.codex_credential_state IS NULL
           OR account.codex_execution_status IS NULL
        """
    )
    cur.execute(
        f"""
        UPDATE {postgres_store.qualified(record_store.ACCOUNTS.name)} account
        SET deactivated=(
            LOWER(COALESCE(account.data->>'account_status', ''))='deactivated'
            OR LOWER(COALESCE(account.codex_status, ''))='deactivated'
            OR LOWER(COALESCE(account.codex_credential_state, ''))='deactivated'
        )
        WHERE account.deactivated IS DISTINCT FROM (
            LOWER(COALESCE(account.data->>'account_status', ''))='deactivated'
            OR LOWER(COALESCE(account.codex_status, ''))='deactivated'
            OR LOWER(COALESCE(account.codex_credential_state, ''))='deactivated'
        )
        """
    )


def _ensure_operation_schema(domain_id: str) -> None:
    with _common._connect() as conn, conn.cursor() as cur:
        if not _FORCE_SCHEMA_CHECK and _migration_completed(cur, domain_id):
            return
        record_store.lock_task_schema(conn, _common._schema_name())
        if not _FORCE_SCHEMA_CHECK and _migration_completed(cur, domain_id):
            return
        _apply_operation_schema(cur)
        table = _common._table(_SCHEMA_MIGRATIONS)
        cur.execute(f"CREATE TABLE IF NOT EXISTS {table} (domain_id TEXT, version INTEGER, PRIMARY KEY (domain_id, version))")
        cur.execute(f"INSERT INTO {table} (domain_id, version) VALUES (%s, %s) ON CONFLICT DO NOTHING", (domain_id, _SCHEMA_VERSION))


def init_operation_schema() -> None:
    """初始化统一任务表与结算域，并对齐历史账号状态。"""
    global _READY_KEY, _FORCE_SCHEMA_CHECK
    # 历史运行结算只能访问启动时已经初始化的原数据域。
    if _common.current_settlement_domain() is not None:
        return
    if not postgres_store.enabled():
        raise RuntimeError("统一任务存储需要配置可用的 DATABASE_URL")
    # 统一任务表仍引用账号记录和旧账号任务表。
    record_store.init()
    account_task_store.init()
    from core.storage.operations import permits

    ready_key = _ready_key()
    with _LOCK:
        if _READY_KEY == ready_key:
            return
        _ensure_operation_schema(permits._settlement_domain().domain_id)
        # 冷启动仍补齐新增记录的兼容状态，在提交统一任务表 DDL 后执行。
        with _common._connect() as conn, conn.cursor() as cur:
            record_store.advisory_xact_lock(conn, f"operation-account-backfill:{postgres_store.schema_name()}")
            _backfill_account_states(cur)
        permits.ensure_tables()
        _READY_KEY = ready_key
        _FORCE_SCHEMA_CHECK = False


def init() -> None:
    init_operation_schema()
    # Remail 意图与统一任务中心共用当前 PostgreSQL schema；建表仍是增量、幂等迁移。
    from core.storage.email import remail_orders

    remail_orders.init()


def reset_ready() -> None:
    reset_operation_ready()
    from core.storage.email import remail_orders

    remail_orders._READY_KEY = ""


