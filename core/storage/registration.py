def finish_run(
    run_id: int,
    *,
    status: str,
    error_code: str | None = None,
    error_message: str | None = None,
    result_summary: dict | None = None,
) -> dict:
    value = str(status or "").strip().lower()
    if value not in RUN_STATUSES:
        raise ValueError(f"未知 RegistrationRun 状态: {status!r}")
    init()
    with _connect() as conn, conn.cursor() as cur:
        cur.execute(f"SELECT * FROM {_table('registration_runs')} WHERE id=%s FOR UPDATE", (int(run_id),))
        run = cur.fetchone()
        if run is None:
            raise LookupError(f"RegistrationRun 不存在: {run_id}")
        completed = _now() if value in TERMINAL_RUN_STATUSES else None
        cur.execute(
            f"""
            UPDATE {_table('registration_runs')}
            SET status=%s, error_code=%s, error_message=%s, result_summary=%s::jsonb,
                completed_at=%s, duration_ms=CASE WHEN started_at IS NULL OR %s IS NULL THEN duration_ms
                    ELSE GREATEST(0, EXTRACT(EPOCH FROM (%s-started_at))*1000)::BIGINT END,
                heartbeat_at=%s
            WHERE id=%s
            RETURNING *
            """,
            (value, error_code, str(error_message or "")[:2000] or None, _json(result_summary or {}),
             completed, completed, completed, _now(), int(run_id)),
        )
        updated = _row(cur.fetchone()) or {}
        if value in {"request_unknown", "manual_reconcile"}:
            _insert_event(
                cur, attempt_id=int(run["attempt_id"]), run_id=int(run_id), job_id=run.get("job_id"),
                checkpoint="manual_reconcile", event_type=value, level="WARNING",
                message=error_message or value, detail=result_summary, execution_id=run.get("execution_id"), event_uuid=None,
            )
        return updated


def recover_interrupted_runs() -> int:
    """Close queued/running registration runs left by a crashed worker.

    Recovery only changes statuses and appends facts; it never deletes attempts,
    runs, events, or legacy jobs.
    """
    init()
    recovered = 0
    with _connect() as conn, conn.cursor() as cur:
        cur.execute(
            f"SELECT * FROM {_table('registration_runs')} WHERE status IN ('queued','running') ORDER BY id FOR UPDATE"
        )
        rows = cur.fetchall()
        for run in rows:
            completed = _now()
            cur.execute(
                f"""
                UPDATE {_table('registration_runs')}
                SET status='interrupted', completed_at=%s,
                    error_code='worker_interrupted',
                    error_message='执行进程中断，等待同一 Attempt 恢复', heartbeat_at=%s
                WHERE id=%s
                """,
                (completed, completed, int(run["id"])),
            )
            cur.execute(
                f"UPDATE {_table('registration_attempts')} SET active_execution_id=NULL, updated_at=%s WHERE id=%s",
                (completed, int(run["attempt_id"])),
            )
            _insert_event(
                cur, attempt_id=int(run["attempt_id"]), run_id=int(run["id"]),
                job_id=run.get("job_id"), checkpoint="manual_reconcile", event_type="run_interrupted",
                level="WARNING", message="执行进程中断，等待同一 Attempt 恢复",
                detail={"run_id": int(run["id"])}, execution_id=run.get("execution_id"),
                event_uuid=str(uuid.uuid5(uuid.NAMESPACE_URL, f"turb-registration-interrupted:{run['id']}")),
            )
            recovered += 1
    return recovered


def persist_core_account(
    attempt_id: int,
    *,
    access_token: str,
    account: dict | None = None,
    run_id: int | None = None,
    job_id: int | None = None,
    execution_id: str | None = None,
) -> dict:
    """Persist the core account immediately after Token acquisition, atomically."""
    token = str(access_token or "").strip()
    if not token:
        raise ValueError("核心账号落库需要 access_token")
    init()
    payload = dict(account or {})
    with _connect() as conn, conn.cursor() as cur:
        cur.execute(f"SELECT * FROM {_table('registration_attempts')} WHERE id=%s FOR UPDATE", (int(attempt_id),))
        attempt = _row(cur.fetchone())
        if attempt is None:
            raise LookupError(f"注册 Attempt 不存在: {attempt_id}")
        current_checkpoint = str(attempt.get("checkpoint") or "created")
        if current_checkpoint not in CHECKPOINT_RANK:
            current_checkpoint = "created"
        if CHECKPOINT_RANK[current_checkpoint] > CHECKPOINT_RANK["core_persisted"]:
            raise ValueError(f"核心账号落库不能倒退已完成的 checkpoint: {current_checkpoint}")
        email = str(payload.get("email") or attempt.get("email") or attempt.get("email_snapshot") or "").strip()
        if not email:
            raise ValueError("核心账号落库需要 email")
        payload["email"] = email
        payload["access_token"] = token
        account_id = payload.get("id") or attempt.get("account_id")
        if account_id is not None:
            cur.execute(
                f"SELECT * FROM {postgres_store.qualified(record_store.ACCOUNTS.name)} WHERE id=%s",
                (int(account_id),),
            )
            existing = cur.fetchone()
            if existing is None:
                payload["id"] = int(account_id)
                account_id = record_store.insert_row(record_store.ACCOUNTS, payload, conn=conn)
            else:
                record_store.patch_row(record_store.ACCOUNTS, int(account_id), payload, conn=conn)
        else:
            account_id = record_store.upsert_row_by(record_store.ACCOUNTS, "email", payload, conn=conn)
        now = _now()
        cur.execute(
            f"""
            UPDATE {_table('registration_attempts')}
            SET account_id=%s, checkpoint='core_persisted', local_account_state='persisted',
                remote_account_state='confirmed',
                target_status='account_available', updated_at=%s, heartbeat_at=%s,
                active_execution_id=COALESCE(%s, active_execution_id)
            WHERE id=%s
            """,
            (int(account_id), now, now, str(execution_id or "").strip() or None, int(attempt_id)),
        )
        _insert_event(
            cur, attempt_id=int(attempt_id), run_id=run_id, job_id=job_id, checkpoint="core_persisted",
            event_type="core_persisted", level="INFO", message="Token 后核心账号已落库",
            detail={"account_id": int(account_id), "email": email}, execution_id=execution_id, event_uuid=None,
        )
        if job_id is not None:
            cur.execute(f"UPDATE {_table('registration_jobs')} SET account_id=%s, attempt_id=%s WHERE id=%s", (int(account_id), int(attempt_id), int(job_id)))
        cur.execute(
            f"SELECT * FROM {postgres_store.qualified(record_store.ACCOUNTS.name)} WHERE id=%s",
            (int(account_id),),
        )
        saved = record_store.merge_row(record_store.ACCOUNTS, cur.fetchone())
        return {"attempt": _attempt_from_cursor(cur, int(attempt_id)), "account": saved, "account_id": int(account_id)}


