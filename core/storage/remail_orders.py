# -*- coding: utf-8 -*-
"""Remail 领取意图的 PostgreSQL 持久层。

这个模块只保存订单关联事实和私有恢复资料，不执行供应商 HTTP 请求。所有写入
都限定当前测试/运行 schema；``private_json`` 仅由协调器内部读取，不作为列表
接口返回值。
"""
from __future__ import annotations

import hashlib
import json
import re
import uuid
from datetime import datetime, timezone
from typing import Any

from core import postgres_store

_READY_KEY = ""
_IDENTIFIER_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
_STATUSES = {"prepared", "submitting", "request_unknown", "order_created", "delivered", "rejected", "read_blocked"}
_PUBLIC_FIELDS = (
    "acquisition_id", "owner_kind", "owner_id", "project_id", "email_suffix",
    "service_mode", "supply_policy", "status", "order_no", "order_created_at",
    "submitted_at", "response_at", "verified_at", "cause_code", "unknown_scope",
    "operation_phase", "http_status", "safe_details", "created_at", "updated_at",
)


def _schema() -> str:
    value = str(postgres_store.schema_name() or "public").strip()
    if not _IDENTIFIER_RE.fullmatch(value):
        raise ValueError("非法 PostgreSQL schema 名称")
    return value


def _table() -> str:
    return f'{postgres_store.quote_identifier(_schema())}."remail_order_intents"'


def _connect():
    from psycopg.rows import dict_row
    return postgres_store.connect(row_factory=dict_row)


def _now() -> datetime:
    return datetime.now(timezone.utc)


def _json(value: Any) -> str:
    return json.dumps(value if value is not None else {}, ensure_ascii=False, separators=(",", ":"))


def _decode(value: Any, default=None):
    if isinstance(value, (dict, list)):
        return value
    try:
        parsed = json.loads(value or "{}")
    except (TypeError, ValueError):
        return {} if default is None else default
    return parsed


def parameter_fingerprint(*, project_id: int, email_suffix: str, service_mode: str, supply_policy: str) -> str:
    raw = f"{int(project_id)}\0{str(email_suffix).strip().lower()}\0{str(service_mode).strip().lower()}\0{str(supply_policy).strip().lower()}"
    return hashlib.sha256(raw.encode("utf-8")).hexdigest()


def init() -> None:
    global _READY_KEY
    if not postgres_store.enabled():
        raise RuntimeError("Remail 订单存储需要配置可用的 DATABASE_URL")
    postgres_store.ensure_schema()
    key = f"{postgres_store.database_url()}::{_schema()}"
    if _READY_KEY == key:
        return
    with _connect() as conn, conn.cursor() as cur:
        cur.execute(
            f"""
            CREATE TABLE IF NOT EXISTS {_table()} (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                acquisition_id TEXT NOT NULL UNIQUE,
                owner_kind TEXT NOT NULL,
                owner_id TEXT NOT NULL,
                supplier_identity_ref TEXT NOT NULL DEFAULT '',
                project_id INTEGER NOT NULL,
                email_suffix TEXT NOT NULL,
                service_mode TEXT NOT NULL,
                supply_policy TEXT NOT NULL,
                parameter_fingerprint TEXT NOT NULL,
                idempotency_key TEXT NOT NULL UNIQUE,
                execution_token TEXT,
                status TEXT NOT NULL DEFAULT 'prepared',
                order_no TEXT,
                order_created_at TIMESTAMPTZ,
                submitted_at TIMESTAMPTZ,
                response_at TIMESTAMPTZ,
                verified_at TIMESTAMPTZ,
                cause_code TEXT,
                unknown_scope TEXT,
                operation_phase TEXT,
                http_status INTEGER,
                safe_details JSONB NOT NULL DEFAULT '{{}}'::jsonb,
                request_json JSONB NOT NULL DEFAULT '{{}}'::jsonb,
                private_json JSONB NOT NULL DEFAULT '{{}}'::jsonb,
                created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
                updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
                UNIQUE(owner_kind, owner_id)
            )
            """
        )
        cur.execute(f"CREATE INDEX IF NOT EXISTS remail_order_intents_status_idx ON {_table()} (status, updated_at)")
    _READY_KEY = key


def _public(row: dict | None) -> dict | None:
    if not row:
        return None
    value = {key: row.get(key) for key in _PUBLIC_FIELDS if key in row}
    value["safe_details"] = _decode(value.get("safe_details"), {})
    return value


def _row(row: dict | None, *, private: bool = False) -> dict | None:
    if not row:
        return None
    value = dict(row)
    value["safe_details"] = _decode(value.get("safe_details"), {})
    value["request_json"] = _decode(value.get("request_json"), {})
    if private:
        value["private_json"] = _decode(value.get("private_json"), {})
    else:
        value.pop("private_json", None)
        value.pop("execution_token", None)
    return value


def get_intent(acquisition_id: str, *, private: bool = False) -> dict | None:
    init()
    with _connect() as conn, conn.cursor() as cur:
        cur.execute(f"SELECT * FROM {_table()} WHERE acquisition_id=%s", (str(acquisition_id),))
        return _row(cur.fetchone(), private=private)


def get_by_owner(owner_kind: str, owner_id: str, *, private: bool = False) -> dict | None:
    init()
    with _connect() as conn, conn.cursor() as cur:
        cur.execute(f"SELECT * FROM {_table()} WHERE owner_kind=%s AND owner_id=%s", (str(owner_kind), str(owner_id)))
        return _row(cur.fetchone(), private=private)


def create_intent(*, acquisition_id: str, owner_kind: str, owner_id: str,
                  supplier_identity_ref: str, project_id: int, email_suffix: str,
                  service_mode: str, supply_policy: str, idempotency_key: str,
                  request_json: dict | None = None) -> dict:
    """并发下按 owner/acquisition 幂等创建 prepared 意图。"""
    init()
    acquisition_id = str(acquisition_id or "").strip()
    owner_kind, owner_id = str(owner_kind or "").strip(), str(owner_id or "").strip()
    if not acquisition_id or not owner_kind or not owner_id:
        raise ValueError("Remail 领取意图缺少 owner 或 acquisition_id")
    values = (
        acquisition_id, owner_kind, owner_id, str(supplier_identity_ref or ""), int(project_id),
        str(email_suffix).strip().lstrip("@"), str(service_mode).strip().lower(),
        str(supply_policy).strip().lower(), parameter_fingerprint(project_id=int(project_id), email_suffix=email_suffix, service_mode=service_mode, supply_policy=supply_policy),
        str(idempotency_key or "").strip() or f"turb-remail-{uuid.uuid4().hex}", _json(request_json or {}),
    )
    with _connect() as conn, conn.cursor() as cur:
        cur.execute(
            f"""
            INSERT INTO {_table()}(acquisition_id,owner_kind,owner_id,supplier_identity_ref,project_id,email_suffix,service_mode,supply_policy,parameter_fingerprint,idempotency_key,request_json)
            VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s::jsonb)
            ON CONFLICT (owner_kind, owner_id) DO NOTHING
            RETURNING *
            """, values,
        )
        row = cur.fetchone()
        if row is None:
            cur.execute(f"SELECT * FROM {_table()} WHERE owner_kind=%s AND owner_id=%s FOR UPDATE", (owner_kind, owner_id))
            row = cur.fetchone()
            if row is None:
                raise RuntimeError("Remail 领取意图创建失败")
            if str(row["acquisition_id"]) != acquisition_id:
                raise RuntimeError("该 owner 已绑定其他 Remail 领取意图")
        return _row(row, private=True) or {}


def claim_submitting(acquisition_id: str, execution_token: str) -> dict | None:
    """prepared 只能由一个执行令牌推进为 submitting；其他状态绝不重发。"""
    init()
    with _connect() as conn, conn.cursor() as cur:
        cur.execute(
            f"""UPDATE {_table()} SET status='submitting', execution_token=%s, submitted_at=COALESCE(submitted_at,now()), updated_at=now()
                WHERE acquisition_id=%s AND status='prepared' RETURNING *""", (str(execution_token), str(acquisition_id)),
        )
        return _row(cur.fetchone(), private=True)


def mark_status(acquisition_id: str, status: str, *, safe_details: dict | None = None,
                order_no: str | None = None, private_json: dict | None = None,
                expected_statuses: tuple[str, ...] | list[str] | None = None,
                execution_token: str | None = None) -> dict | None:
    init()
    status = str(status or "").strip().lower()
    if status not in _STATUSES:
        raise ValueError(f"未知 Remail 订单状态: {status}")
    sets = ["status=%s", "updated_at=now()"]
    params: list[Any] = [status]
    if status in {"order_created", "delivered", "request_unknown", "rejected", "read_blocked"}:
        sets.append("response_at=COALESCE(response_at,now())")
    if status == "delivered":
        sets.append("verified_at=now()")
    if order_no:
        sets += ["order_no=COALESCE(order_no,%s)", "order_created_at=COALESCE(order_created_at,now())"]
        params.append(str(order_no))
    if safe_details is not None:
        sets += ["safe_details=%s::jsonb", "cause_code=%s", "unknown_scope=%s", "operation_phase=%s", "http_status=%s"]
        params.extend((_json(safe_details), safe_details.get("cause_code"), safe_details.get("unknown_scope"), safe_details.get("operation_phase"), safe_details.get("http_status")))
    if private_json is not None:
        sets.append("private_json=private_json || %s::jsonb")
        params.append(_json(private_json))
    where = ["acquisition_id=%s"]
    params.append(str(acquisition_id))
    if expected_statuses:
        where.append("status = ANY(%s)")
        params.append(list(expected_statuses))
    if execution_token is not None:
        where.append("execution_token=%s")
        params.append(str(execution_token))
    with _connect() as conn, conn.cursor() as cur:
        cur.execute(f"UPDATE {_table()} SET {', '.join(sets)} WHERE {' AND '.join(where)} RETURNING *", tuple(params))
        return _row(cur.fetchone(), private=True)


def list_reconciliation(*, limit: int = 100) -> list[dict]:
    init()
    with _connect() as conn, conn.cursor() as cur:
        cur.execute(f"SELECT * FROM {_table()} WHERE status IN ('submitting','request_unknown','order_created','read_blocked') ORDER BY updated_at LIMIT %s", (max(1, min(int(limit), 1000)),))
        return [_public(row) for row in cur.fetchall()]


def public_summary(intent: dict | None) -> dict:
    if not intent:
        return {}
    details = _decode(intent.get("safe_details"), {})
    return {
        "acquisition_id": intent.get("acquisition_id"), "owner_kind": intent.get("owner_kind"),
        "owner_id": intent.get("owner_id"), "status": intent.get("status"),
        "has_order_no": bool(intent.get("order_no")),
        "has_delivery_credentials": bool(_decode(intent.get("private_json"), {}).get("email")),
        "email": str(_decode(intent.get("private_json"), {}).get("email") or "")[:3] + "***" if _decode(intent.get("private_json"), {}).get("email") else None,
        "cause_code": details.get("cause_code") or intent.get("cause_code"),
        "unknown_scope": details.get("unknown_scope") or intent.get("unknown_scope"),
        "allowed_actions": ["verify_original_order"] if intent.get("status") in {"submitting", "request_unknown", "order_created", "read_blocked"} else [],
    }


# 领域命名兼容别名，避免调用方把“订单”与“意图”混用时另建一套存储。
create_order_intent = create_intent
get_order_intent = get_intent
claim_order_submission = claim_submitting
