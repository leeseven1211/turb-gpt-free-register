"""付费邮箱供应商的订单、幂等键与取码游标；PostgreSQL 是唯一事实来源。"""
from __future__ import annotations

from contextlib import contextmanager
import hashlib
import json
import os
import uuid
import threading

from psycopg.rows import dict_row

from core import postgres_store

_READY_KEY = ""
_PROVIDERS = {"mailcode", "xigua"}
_INIT_LOCK = threading.RLock()
_LOCK_SLOT_GUARD = threading.Lock()
_LOCK_SLOTS: dict[str, threading.BoundedSemaphore] = {}


def _table():
    return f'{postgres_store.quote_identifier(postgres_store.schema_name())}."mail_provider_orders"'


def _connect():
    return postgres_store.connect(row_factory=dict_row)


def init():
    with _INIT_LOCK:
        _init()


def _init():
    global _READY_KEY
    if not postgres_store.enabled():
        raise RuntimeError("付费邮箱订单需要配置 PostgreSQL DATABASE_URL")
    postgres_store.ensure_schema()
    key = (postgres_store.database_url(), postgres_store.schema_name())
    if _READY_KEY == key:
        return
    with _connect() as conn, conn.cursor() as cur:
        # 两个 WebUI/worker 进程同时首次使用供应商时，DDL 也要串行。
        cur.execute("SELECT pg_advisory_xact_lock(hashtext(%s))", (f"mail-provider-ddl:{postgres_store.schema_name()}",))
        cur.execute(f"""CREATE TABLE IF NOT EXISTS {_table()} (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            provider TEXT NOT NULL,
            owner_kind TEXT NOT NULL,
            owner_id TEXT NOT NULL,
            acquisition_id TEXT NOT NULL,
            supplier_ref TEXT NOT NULL,
            idempotency_key TEXT NOT NULL UNIQUE,
            request_json JSONB NOT NULL DEFAULT '{{}}'::jsonb,
            status TEXT NOT NULL DEFAULT 'prepared',
            email TEXT NOT NULL DEFAULT '',
            order_id TEXT NOT NULL DEFAULT '',
            private_json JSONB NOT NULL DEFAULT '{{}}'::jsonb,
            created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
            updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
            UNIQUE(provider, owner_kind, owner_id),
            UNIQUE(provider, acquisition_id)
        )""")
        cur.execute(f"""CREATE UNIQUE INDEX IF NOT EXISTS mail_provider_orders_email_idx
            ON {_table()} (provider, supplier_ref, lower(email)) WHERE email <> ''""")
    _READY_KEY = key


def supplier_ref(base: str, key: str) -> str:
    return hashlib.sha256((base + "\0" + key).encode()).hexdigest()


@contextmanager
def order_lock(provider: str, identity: str):
    """跨进程串行化同一个领取/取码操作，不把 HTTP 写入藏在事务重试中。"""
    init()
    from core.mailbox_wait import bounded_sleep, current_budget

    # 和专用连接池一样按数据库复用名额，并在首次使用时固定容量。排队不先
    # 借连接，因此供应商慢请求不会令第 13 个以上的任务触发池的 10 秒超时。
    with _LOCK_SLOT_GUARD:
        pool_key = postgres_store.database_url()
        slots = _LOCK_SLOTS.get(pool_key)
        if slots is None:
            slots = threading.BoundedSemaphore(max(1, int(os.getenv("TURB_DB_POOL_MAX") or 12)))
            _LOCK_SLOTS[pool_key] = slots

    def checkpoint():
        budget = current_budget()
        if budget is not None:
            budget.require("等待邮箱订单锁")

    while True:
        checkpoint()
        if slots.acquire(blocking=False):
            break
        bounded_sleep(0.05)
    value = int.from_bytes(hashlib.sha256(f"{provider}\0{identity}".encode()).digest()[:8], "big", signed=True)
    # 锁连接使用独立池；等待供应商时不占用普通读写池，避免批量并发耗尽
    # 普通连接后，已经持锁的任务也无法保存订单而相互等待。
    try:
        checkpoint()
        with postgres_store.connect(row_factory=dict_row, application_name="turb-mail-provider-lock") as conn, conn.cursor() as cur:
            while True:
                checkpoint()
                cur.execute("SELECT pg_try_advisory_xact_lock(%s) AS acquired", (value,))
                if cur.fetchone()["acquired"]:
                    break
                bounded_sleep(0.1)
            yield
    finally:
        slots.release()


def get_by_owner(provider: str, owner_kind: str, owner_id: str):
    init()
    with _connect() as conn, conn.cursor() as cur:
        cur.execute(f"SELECT * FROM {_table()} WHERE provider=%s AND owner_kind=%s AND owner_id=%s",
                    (provider, str(owner_kind), str(owner_id)))
        return cur.fetchone()


def get_by_email(provider: str, email: str, *, identity: str | None = None):
    init()
    clauses, params = ["provider=%s", "lower(email)=%s"], [provider, str(email).strip().lower()]
    if identity:
        clauses.append("supplier_ref=%s")
        params.append(identity)
    with _connect() as conn, conn.cursor() as cur:
        cur.execute(f"SELECT * FROM {_table()} WHERE {' AND '.join(clauses)} LIMIT 2", tuple(params))
        rows = cur.fetchall()
    if len(rows) > 1:
        raise RuntimeError("同一邮箱存在多个供应商身份，必须恢复原订单身份")
    return rows[0] if rows else None


def find_source(email: str):
    init()
    with _connect() as conn, conn.cursor() as cur:
        cur.execute(f"SELECT DISTINCT provider FROM {_table()} WHERE lower(email)=%s", (str(email).strip().lower(),))
        providers = [row["provider"] for row in cur.fetchall()]
    return providers[0] if len(providers) == 1 else None


def prepare(*, provider: str, owner_kind: str, owner_id: str, acquisition_id: str | None,
            identity: str, request: dict):
    init()
    if provider not in _PROVIDERS or not owner_kind or not str(owner_id):
        raise ValueError("付费邮箱领取缺少稳定的 provider/owner")
    stable_id = str(acquisition_id or f"{provider}:{owner_kind}:{owner_id}")
    with _connect() as conn, conn.cursor() as cur:
        cur.execute(f"""INSERT INTO {_table()}
            (provider,owner_kind,owner_id,acquisition_id,supplier_ref,idempotency_key,request_json)
            VALUES (%s,%s,%s,%s,%s,%s,%s::jsonb)
            ON CONFLICT (provider,owner_kind,owner_id) DO NOTHING RETURNING *""",
            (provider, str(owner_kind), str(owner_id), stable_id, identity,
             f"turb-{provider}-{uuid.uuid4().hex}", json.dumps(request)))
        row = cur.fetchone()
        if row is None:
            cur.execute(f"SELECT * FROM {_table()} WHERE provider=%s AND owner_kind=%s AND owner_id=%s",
                        (provider, str(owner_kind), str(owner_id)))
            row = cur.fetchone()
    if not row or row["supplier_ref"] != identity or row["acquisition_id"] != stable_id:
        raise RuntimeError("原付费邮箱订单身份与当前任务或供应商配置不匹配，请恢复原配置重跑")
    # 原请求是恢复事实；任务重跑不因当前商品配置变化而改购其他邮箱。
    return row


def update(order_pk: int, *, status: str | None = None, email: str | None = None,
           order_id: str | None = None, private: dict | None = None):
    init()
    sets, params = ["updated_at=now()"], []
    for column, value in (("status", status), ("email", email), ("order_id", order_id)):
        if value is not None:
            sets.append(f"{column}=%s")
            params.append(value)
    if private is not None:
        sets.append("private_json=private_json || %s::jsonb")
        params.append(json.dumps(private))
    params.append(int(order_pk))
    with _connect() as conn, conn.cursor() as cur:
        cur.execute(f"UPDATE {_table()} SET {', '.join(sets)} WHERE id=%s RETURNING *", tuple(params))
        return cur.fetchone()
