"""Private storage for account-scoped Protocol authentication identities.

This module deliberately does not use :mod:`core.record_store`'s generic JSON
collections.  A stable auth identity contains device-level identifiers that
must not leak into ``registered_accounts.data``, compatibility exports, task
payloads, or ordinary account APIs.

The identity is opt-in and lazy.  Callers must explicitly choose the
``account_stable`` profile mode before invoking ``ensure_*``; this module does
not make that policy decision for them.
"""
