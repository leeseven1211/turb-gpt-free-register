"""密码重置的私有密文检查点、执行围栏及原子换密。

本表独立于诊断及任务历史，未完成候选不会被历史清理级联删除。
旧密码留在密文历史中，普通账号及注册任务投影不读取本表。
"""
from __future__ import annotations

import base64
import hashlib
import hmac
import json
import os
import threading
from contextlib import contextmanager
from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import Callable

import psycopg
from cryptography.fernet import Fernet, InvalidToken
from psycopg.rows import dict_row
from psycopg_pool import PoolTimeout

from core.storage import postgres as pg, records as records
from core.storage.operations import store as operations

_TABLE = "account_password_recoveries"
_READY_KEY = ""
_LOCK = threading.RLock()
_ACTIVE = {"running", "cancelling", "settling"}
_CONFIRMATIONS = {"password_change_response", "candidate_login"}


class PasswordRecoveryError(RuntimeError):
    """对上层只提供稳定类别，不输出凭据或数据库异常详情。"""

    def __init__(self, code: str):
        self.code = code
        super().__init__(f"密码恢复失败：{code}")


@dataclass(frozen=True)
class PrivateCheckpoint:
    recovery_id: int
    state: str
    version: int
    account_id: int
    email: str
    purpose: str
    operation_run_id: int
    operation_execution_id: str
    attempt_id: int | None
    registration_run_id: int | None
    registration_execution_id: str | None
    account_password_version: str = field(repr=False)
    old_password: str = field(repr=False)
    password: str = field(repr=False)


@dataclass(frozen=True)
class _Owner:
    email: str
    account_id: int
    purpose: str
    operation_run_id: int
    operation_execution_id: str
    operation_lease_token: str | None = field(default=None, repr=False)
    attempt_id: int | None = None
    registration_run_id: int | None = None
    registration_execution_id: str | None = None


@contextmanager
def _database_errors():
    try:
        yield
    except (psycopg.Error, PoolTimeout) as exc:
        raise PasswordRecoveryError(f"database_{getattr(exc, 'sqlstate', None) or type(exc).__name__}") from None


def init() -> None:
    """按当前 schema 懒初始化；不向公开 records 集合注册私有表。"""
    global _READY_KEY
    key = f"{pg.database_url()}::{pg.schema_name()}"
    with _LOCK:
        if key == _READY_KEY:
            return
        with _database_errors():
            operations.init()
            with pg.connect() as conn, conn.cursor() as cur:
                cur.execute(f"""
                    CREATE TABLE IF NOT EXISTS {pg.qualified(_TABLE)} (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        account_id BIGINT NOT NULL,
                        email TEXT NOT NULL,
                        purpose TEXT NOT NULL CHECK (purpose IN ('registration','manual')),
                        state TEXT NOT NULL CHECK (state IN ('prepared','started','unknown','confirmed')),
                        version INTEGER NOT NULL DEFAULT 1,
                        operation_run_id BIGINT NOT NULL,
                        operation_execution_id TEXT NOT NULL,
                        attempt_id BIGINT,
                        registration_run_id BIGINT,
                        registration_execution_id TEXT,
                        credential_ciphertext TEXT NOT NULL,
                        confirmation TEXT,
                        created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
                        updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
                        confirmed_at TIMESTAMPTZ
                    )
                """)
                cur.execute(f"CREATE UNIQUE INDEX IF NOT EXISTS account_password_recoveries_pending_idx "
                            f"ON {pg.qualified(_TABLE)} (account_id,lower(email)) WHERE state<>'confirmed'")
        _READY_KEY = key


def _cipher() -> tuple[Fernet, bytes]:
    key = str(os.getenv("TURB_CONFIG_ENCRYPTION_KEY") or "").strip()
    if not key:
        raise PasswordRecoveryError("encryption_key_missing")
    try:
        return Fernet(key.encode("ascii")), base64.urlsafe_b64decode(key)
    except (ValueError, UnicodeError):
        raise PasswordRecoveryError("encryption_key_invalid") from None


def _owner(values: dict) -> _Owner:
    try:
        owner = _Owner(**values)
        if (not str(owner.email).strip() or int(owner.account_id) < 1 or int(owner.operation_run_id) < 1
                or not str(owner.operation_execution_id or "").strip()
                or owner.purpose not in {"registration", "manual"}):
            raise ValueError()
        if owner.purpose == "registration":
            if not owner.attempt_id or not owner.registration_run_id or not owner.registration_execution_id:
                raise ValueError()
        elif any(value is not None for value in (owner.attempt_id, owner.registration_run_id, owner.registration_execution_id)):
            raise ValueError()
        return _Owner(**{**values, "email": str(owner.email).strip().casefold(), "account_id": int(owner.account_id),
                         "operation_run_id": int(owner.operation_run_id)})
    except (TypeError, ValueError):
        raise PasswordRecoveryError("owner_invalid") from None


def _json_object(value) -> dict:
    if isinstance(value, dict):
        return dict(value)
    try:
        decoded = json.loads(value or "{}")
        if isinstance(decoded, dict):
            return decoded
    except (TypeError, ValueError):
        pass
    raise PasswordRecoveryError("credential_context_invalid")


def _password(account: dict) -> str:
    extra = _json_object(account.get("extra_json"))
    for source in (extra, account):
        for key in ("account_password", "login_password", "registration_password"):
            value = str(source.get(key) or "").strip()
            if value:
                return value
    return ""


def _password_version(owner: _Owner, password: str, key: bytes) -> str:
    material = json.dumps(["turb-password-recovery:v1", owner.account_id, owner.email, password], ensure_ascii=False)
    return hmac.new(key, material.encode(), hashlib.sha256).hexdigest()


def _fence(cur, owner: _Owner) -> tuple[dict, list[dict]]:
    """按 Run → 关联 Attempt → 账号锁定，与普通注册凭据写入保持同向。"""
    cur.execute(f"SELECT * FROM {pg.qualified('operation_runs')} WHERE id=%s FOR UPDATE", (owner.operation_run_id,))
    run = cur.fetchone()
    if not run or run["status"] not in _ACTIVE or run.get("cancel_requested_at"):
        raise PasswordRecoveryError("operation_inactive")
    if str(run.get("execution_id") or "") != owner.operation_execution_id:
        raise PasswordRecoveryError("operation_execution_mismatch")
    cur.execute(f"SELECT * FROM {pg.qualified('operation_tasks')} WHERE id=%s", (run["task_id"],))
    task = cur.fetchone() or {}
    if ((task.get("account_id") is not None and int(task["account_id"]) != owner.account_id)
            or (run.get("account_id") is not None and int(run["account_id"]) != owner.account_id)
            or (task.get("email_snapshot") and str(task["email_snapshot"]).strip().casefold() != owner.email)):
        raise PasswordRecoveryError("operation_identity_mismatch")
    # 提前锁定所有需要同步的原 Attempt；确认阶段复用此快照，持有账号锁后不再补锁。
    cur.execute(f"SELECT * FROM {pg.qualified('registration_attempts')} "
                "WHERE account_id=%s AND lower(COALESCE(NULLIF(email_snapshot,''),email))=%s ORDER BY id FOR UPDATE",
                (owner.account_id, owner.email))
    attempts = cur.fetchall()
    if owner.purpose == "registration":
        attempt = next((item for item in attempts if item["id"] == owner.attempt_id), {})
        if not attempt or attempt.get("active_execution_id") != owner.registration_execution_id:
            raise PasswordRecoveryError("registration_identity_mismatch")
        # start_run/finish_run 均在事务内锁定或更新 Attempt；依靠已持有的 Attempt
        # 锁串行化归属变更，避免与 finish_run 的 Run → Attempt 顺序反向加锁。
        cur.execute(f"SELECT * FROM {pg.qualified('registration_runs')} WHERE id=%s", (owner.registration_run_id,))
        registration_run = cur.fetchone() or {}
        if (registration_run.get("attempt_id") != owner.attempt_id or registration_run.get("status") != "running"
                or registration_run.get("execution_id") != owner.registration_execution_id
                or registration_run.get("action_type") not in {"registration", "registration_resume"}):
            raise PasswordRecoveryError("registration_execution_mismatch")
        cur.execute(f"SELECT * FROM {pg.qualified('registration_jobs')} WHERE id=%s", (registration_run.get("job_id"),))
        job = cur.fetchone() or {}
        # Job 可不保存注册 worker 的执行标识；该标识由活动 Attempt 与
        # RegistrationRun 共同确认，兼容操作 Run 则始终绑定 Job.job_uuid。
        if (job.get("attempt_id") != owner.attempt_id or job.get("status") != "running"
                or (job.get("execution_id") and job["execution_id"] != owner.registration_execution_id)
                or str(job.get("email") or "").strip().casefold() != owner.email
                or (job.get("account_id") is not None and job["account_id"] != owner.account_id)
                or run.get("source_system") != "registration_jobs" or run.get("source_id") != str(job.get("id"))
                or run.get("execution_id") != job.get("job_uuid")
                or task.get("attempt_id") != owner.attempt_id
                or task.get("task_type") not in {"registration", "registration_resume"}):
            raise PasswordRecoveryError("registration_operation_mapping_mismatch")
    elif task.get("task_type") != "password_change" or int(run.get("account_id") or 0) != owner.account_id:
        raise PasswordRecoveryError("manual_operation_mismatch")
    account = records.get_row(records.ACCOUNTS, owner.account_id, conn=cur.connection, for_update=True)
    if not account or str(account.get("email") or "").strip().casefold() != owner.email:
        raise PasswordRecoveryError("account_identity_mismatch")
    if any(str(account.get(k) or "").casefold() == "deactivated" for k in ("account_status", "codex_status", "codex_credential_state")):
        raise PasswordRecoveryError("account_deactivated")
    if owner.purpose == "manual":
        cur.execute(f"SELECT 1 FROM {pg.qualified('account_operation_leases')} "
                    "WHERE account_id=%s AND run_id=%s AND lease_token=%s AND expires_at>now() FOR UPDATE",
                    (owner.account_id, owner.operation_run_id, str(owner.operation_lease_token or "")))
        if not cur.fetchone():
            raise PasswordRecoveryError("operation_lease_invalid")
    return account, attempts


def _identity(row: dict, owner: _Owner) -> bool:
    return all(row.get(key) == getattr(owner, key) for key in (
        "account_id", "email", "purpose", "operation_run_id", "operation_execution_id",
        "attempt_id", "registration_run_id", "registration_execution_id"))


def _credentials(row: dict, cipher: Fernet) -> dict:
    try:
        payload = json.loads(cipher.decrypt(row["credential_ciphertext"].encode("ascii")))
        if (payload.get("purpose") != "turb_password_recovery" or payload.get("format_version") != 1
                or payload.get("account_id") != row["account_id"] or payload.get("email") != row["email"]
                or not isinstance(payload.get("old_password"), str) or not payload.get("password")
                or not payload.get("account_password_version")):
            raise ValueError()
        return payload
    except (InvalidToken, ValueError, TypeError, KeyError, UnicodeError, AttributeError):
        raise PasswordRecoveryError("credential_decryption_failed") from None


def _checkpoint(row: dict, cipher: Fernet) -> PrivateCheckpoint:
    payload = _credentials(row, cipher)
    return PrivateCheckpoint(recovery_id=int(row["id"]), **{key: row[key] for key in (
        "state", "version", "account_id", "email", "purpose", "operation_run_id", "operation_execution_id",
        "attempt_id", "registration_run_id", "registration_execution_id")},
        **{key: payload[key] for key in ("account_password_version", "old_password", "password")})


def _takeover(cur, row: dict, owner: _Owner) -> dict:
    if _identity(row, owner):
        return row
    cur.execute(f"SELECT status,execution_id FROM {pg.qualified('operation_runs')} WHERE id=%s", (row["operation_run_id"],))
    prior = cur.fetchone()
    if prior and prior["status"] in _ACTIVE and prior["execution_id"] == row["operation_execution_id"]:
        raise PasswordRecoveryError("owner_active")
    if row.get("registration_run_id"):
        cur.execute(f"SELECT status,execution_id FROM {pg.qualified('registration_runs')} WHERE id=%s", (row["registration_run_id"],))
        prior = cur.fetchone()
        if prior and prior["status"] == "running" and prior["execution_id"] == row["registration_execution_id"]:
            raise PasswordRecoveryError("owner_active")
    if owner.purpose == "registration" and row.get("attempt_id") not in {None, owner.attempt_id}:
        raise PasswordRecoveryError("registration_attempt_conflict")
    cur.execute(f"UPDATE {pg.qualified(_TABLE)} SET purpose=%s,operation_run_id=%s,operation_execution_id=%s,"
                "attempt_id=%s,registration_run_id=%s,registration_execution_id=%s,version=version+1,updated_at=now() WHERE id=%s RETURNING *",
                (owner.purpose, owner.operation_run_id, owner.operation_execution_id, owner.attempt_id,
                 owner.registration_run_id, owner.registration_execution_id, row["id"]))
    return cur.fetchone()


def _prepare_or_resume(owner_values: dict, candidate_factory: Callable[[], str] | None) -> PrivateCheckpoint | None:
    owner = _owner(owner_values)
    cipher, key = _cipher()
    init()
    with _database_errors(), pg.connect(row_factory=dict_row) as conn, conn.cursor() as cur:
        account, attempts = _fence(cur, owner)
        cur.execute(f"SELECT * FROM {pg.qualified(_TABLE)} WHERE account_id=%s AND email=%s AND state<>'confirmed' FOR UPDATE",
                    (owner.account_id, owner.email))
        pending = cur.fetchone()
        if pending:
            _validate_password(owner, account, attempts, _credentials(pending, cipher), key,
                               allow_candidate=pending["state"] in {"started", "unknown"})
            return _checkpoint(_takeover(cur, pending, owner), cipher)
        if candidate_factory is None:
            return None
        old_password = _password(account)
        _validate_attempt_passwords(attempts, {old_password})
        if owner.purpose == "registration" and not old_password:
            raise PasswordRecoveryError("password_conflict")
        try:
            candidate = candidate_factory()
        except Exception:
            raise PasswordRecoveryError("candidate_generation_failed") from None
        if not isinstance(candidate, str) or not candidate.strip() or candidate != candidate.strip() or candidate == old_password:
            raise PasswordRecoveryError("candidate_invalid")
        payload = {"purpose": "turb_password_recovery", "format_version": 1, "account_id": owner.account_id,
                   "email": owner.email, "old_password": old_password, "password": candidate,
                   "account_password_version": _password_version(owner, old_password, key)}
        encrypted = cipher.encrypt(json.dumps(payload, ensure_ascii=False).encode()).decode("ascii")
        cur.execute(f"INSERT INTO {pg.qualified(_TABLE)} (account_id,email,purpose,state,operation_run_id,operation_execution_id,"
                    "attempt_id,registration_run_id,registration_execution_id,credential_ciphertext) "
                    "VALUES (%s,%s,%s,'prepared',%s,%s,%s,%s,%s,%s) RETURNING *",
                    (owner.account_id, owner.email, owner.purpose, owner.operation_run_id, owner.operation_execution_id,
                     owner.attempt_id, owner.registration_run_id, owner.registration_execution_id, encrypted))
        return _checkpoint(cur.fetchone(), cipher)


def prepare_password_recovery(*, candidate_factory: Callable[[], str], **owner) -> PrivateCheckpoint:
    """提交前持久化唯一候选；已存在的未完成候选永远复用。"""
    return _prepare_or_resume(owner, candidate_factory)


def resume_password_recovery(**owner) -> PrivateCheckpoint | None:
    """只恢复待完成候选，允许在原执行结束后交给合法的新执行。"""
    return _prepare_or_resume(owner, None)


def _owned_checkpoint(cur, recovery_id: int, owner: _Owner) -> dict:
    cur.execute(f"SELECT * FROM {pg.qualified(_TABLE)} WHERE id=%s FOR UPDATE", (int(recovery_id),))
    row = cur.fetchone()
    if not row:
        raise PasswordRecoveryError("recovery_not_found")
    if not _identity(row, owner):
        raise PasswordRecoveryError("recovery_owner_mismatch")
    return row


def get_password_recovery(recovery_id: int, **owner) -> PrivateCheckpoint:
    """读取必须仍持有原执行围栏，不能隐式接管。"""
    identity = _owner(owner)
    cipher, _ = _cipher()
    init()
    with _database_errors(), pg.connect(row_factory=dict_row) as conn, conn.cursor() as cur:
        _fence(cur, identity)
        return _checkpoint(_owned_checkpoint(cur, recovery_id, identity), cipher)


def _validate_attempt_passwords(attempts: list[dict], allowed: set[str]) -> None:
    for attempt in attempts:
        private = _json_object(attempt["private_context"])
        if str(private.get("password") or "") not in allowed | {""}:
            raise PasswordRecoveryError("attempt_password_conflict")


def _validate_password(owner: _Owner, account: dict, attempts: list[dict], payload: dict, key: bytes,
                       *, allow_candidate: bool = False, confirmed: bool = False) -> None:
    current = _password(account)
    allowed = {payload["password"]} if confirmed else {payload["old_password"]}
    if allow_candidate:
        allowed.add(payload["password"])
    if current not in allowed or not hmac.compare_digest(
            _password_version(owner, payload["old_password"], key), payload["account_password_version"]):
        raise PasswordRecoveryError("password_conflict")
    _validate_attempt_passwords(attempts, allowed)


def _confirm(cur, row: dict, owner: _Owner, account: dict, attempts: list[dict], payload: dict, key: bytes) -> None:
    candidate = payload["password"]
    _validate_password(owner, account, attempts, payload, key, allow_candidate=True, confirmed=row["state"] == "confirmed")
    if row["state"] == "confirmed":
        return
    extra = _json_object(account.get("extra_json"))
    extra["account_password"] = candidate
    for alias in ("login_password", "login_password_source", "registration_password"):
        extra.pop(alias, None)
    changes = {"extra_json": json.dumps(extra, ensure_ascii=False), "updated_at": datetime.now(timezone.utc).isoformat()}
    for alias in ("account_password", "login_password", "registration_password"):
        if alias in account:
            changes[alias] = candidate
    records.patch_row(records.ACCOUNTS, owner.account_id, changes, conn=cur.connection)
    for attempt in attempts:
        private = _json_object(attempt["private_context"])
        private["password"] = candidate
        history = list(private.get("password_recovery_history") or [])
        history.append({"recovery_id": row["id"], "account_password_version": payload["account_password_version"]})
        private["password_recovery_history"] = history
        cur.execute(f"UPDATE {pg.qualified('registration_attempts')} SET private_context=%s::jsonb,updated_at=now() WHERE id=%s",
                    (json.dumps(private, ensure_ascii=False), attempt["id"]))


def transition_password_recovery(recovery_id: int, *, expected_version: int, state: str,
                                 confirmation: str | None = None, **owner) -> PrivateCheckpoint:
    """推进检查点；明确确认时，同一事务更新账号与关联 Attempt 当前密码。"""
    identity = _owner(owner)
    if state not in {"prepared", "started", "unknown", "confirmed"}:
        raise PasswordRecoveryError("state_invalid")
    if (state == "confirmed" and confirmation not in _CONFIRMATIONS) or (state != "confirmed" and confirmation is not None):
        raise PasswordRecoveryError("confirmation_invalid")
    cipher, key = _cipher()
    init()
    with _database_errors(), pg.connect(row_factory=dict_row) as conn, conn.cursor() as cur:
        account, attempts = _fence(cur, identity)
        row = _owned_checkpoint(cur, recovery_id, identity)
        payload = _credentials(row, cipher)
        if row["state"] == state == "confirmed":
            _confirm(cur, row, identity, account, attempts, payload, key)
            return _checkpoint(row, cipher)
        if row["version"] != expected_version:
            raise PasswordRecoveryError("version_conflict")
        if row["state"] == state:
            return _checkpoint(row, cipher)
        if state not in {"prepared": {"started"}, "started": {"unknown", "confirmed"}, "unknown": {"confirmed"}, "confirmed": set()}[row["state"]]:
            raise PasswordRecoveryError("state_transition_invalid")
        if state == "confirmed":
            _confirm(cur, row, identity, account, attempts, payload, key)
        elif state == "started":
            _validate_password(identity, account, attempts, payload, key)
        cur.execute(f"UPDATE {pg.qualified(_TABLE)} SET state=%s,version=version+1,confirmation=%s,updated_at=now(),"
                    "confirmed_at=CASE WHEN %s='confirmed' THEN now() ELSE confirmed_at END WHERE id=%s RETURNING *",
                    (state, confirmation, state, int(recovery_id)))
        return _checkpoint(cur.fetchone(), cipher)


