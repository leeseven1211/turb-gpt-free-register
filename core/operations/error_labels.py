LOOKUP_FIELDS = ('cause_display_code', 'cause_code', 'code', 'error_code', 'display_code')


def label_for_code(field: str, value: Any) -> str | None:
    """命中结构化细因才返回短语；未登记值留给上一级分类兜底。"""
    code = str(value or '').strip()
    if not code:
        return None
    if field in _DISPLAY_FIELDS:
        exact = DISPLAY_CODE_LABELS.get(code)
    else:
        exact = CAUSE_CODE_LABELS.get(code) or CODE_LABELS.get(code)
    if exact:
        return exact
    for rule in RULES:
        if field in rule['fields'] and re.search(rule['pattern'], code):
            return rule['label']
    return None


def short_error_label(info: Mapping[str, Any] | None) -> str:
    """将既有 error_info 压缩成分类短语；不修改记录、重试资格或远端状态。"""
    info = info if isinstance(info, Mapping) else {}
    for field in LOOKUP_FIELDS:
        found = label_for_code(field, info.get(field))
        if found:
            return found
    for field in ('category', 'source'):
        if found := CATEGORY_LABELS.get(str(info.get(field) or '')):
            return found
    return FALLBACK_LABEL


def label_catalog() -> dict[str, Any]:
    """前端使用相同有序规则，不能自行用原始错误文本重做分类。"""
    return {
        'version': 1, 'maxLength': MAX_LABEL_LENGTH, 'lookupFields': list(LOOKUP_FIELDS),
        'codeLabels': CODE_LABELS, 'causeCodeLabels': CAUSE_CODE_LABELS,
        'displayCodeLabels': DISPLAY_CODE_LABELS, 'categoryLabels': CATEGORY_LABELS,
        'rules': RULES, 'fallback': FALLBACK_LABEL,
    }
